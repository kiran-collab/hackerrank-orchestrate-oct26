"""Evaluation harness: black-box evaluation of the agent's responses.

    python3 code/evaluation/main.py                    # full harness, writes harness_report.md
    python3 code/evaluation/main.py --quick            # skip metamorphic tests
    python3 code/evaluation/main.py --update-baseline  # accept current scores as the regression baseline
    python3 code/evaluation/main.py --score PRED.csv --expected EXP.csv [--requests REQ.csv]

Stages
  1. generate   run code/main.py as a subprocess on each suite; predictions land in evaluation/predictions/
  2. score      metrics.py compares the prediction CSVs with expected answers (sample, custom)
  3. contract   contract.py validates every prediction file, including the 518-row output.csv
  4. robust     metamorphic.py perturbation tests on the 518 evaluation requests
  5. regress    headline metrics vs evaluation/baseline.json (fails on a drop beyond tolerance)
Exit status is non-zero if any contract, robustness, or regression check fails.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
CODE = HERE.parent
REPO = CODE.parent
sys.path.insert(0, str(CODE))

from evaluation import contract, metamorphic, metrics  # noqa: E402

PRED_DIR = HERE / "predictions"
BASELINE = HERE / "baseline.json"
TOLERANCE = 0.005  # allowed absolute drop in a headline metric before the gate fails

SUITES = {
    "sample": (REPO / "dataset", "sample_deletion_requests.csv", REPO / "dataset" / "sample_output.csv"),
    "custom": (HERE / "custom_cases", "deletion_requests.csv", HERE / "custom_cases" / "expected_output.csv"),
}


def headline(m: dict) -> dict:
    return {"status_accuracy": m["status"]["accuracy"], "step_f1": m["steps"]["f1"],
            "sequence_exact": m["sequence"]["exact"], "discovery_f1": m["discovery"]["f1"],
            "findings_f1": m["findings"]["f1"], "evidence_accuracy": m["evidence_accuracy"],
            "policy_agreement": m["policy_agreement"]}


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def render(report: dict) -> str:
    out = ["# Evaluation Harness Report", "",
           f"Generated by `python3 code/evaluation/main.py` in {report['seconds']} s. "
           "Predictions are produced by running `code/main.py` as a subprocess and scored from the CSV files.", ""]
    out += ["## 1. Accuracy against expected answers", "",
            "| Metric | " + " | ".join(report["scores"]) + " |", "|---|" + "---|" * len(report["scores"])]
    rows = [
        ("Cases", lambda m: str(m["cases"])),
        ("Status accuracy", lambda m: pct(m["status"]["accuracy"])),
        ("Step precision", lambda m: pct(m["steps"]["precision"])),
        ("Step recall", lambda m: pct(m["steps"]["recall"])),
        ("Step F1", lambda m: f"{m['steps']['f1']:.3f}"),
        ("Resource discovery F1 (identity resolution)", lambda m: f"{m['discovery']['f1']:.3f}"),
        ("Findings F1 (remaining data, exposure, flows, restore)", lambda m: f"{m['findings']['f1']:.3f}"),
        ("Policy agreement (same operations per resource)", lambda m: pct(m["policy_agreement"])),
        ("Evidence accuracy (matched steps)", lambda m: pct(m["evidence_accuracy"])),
        ("Sequence exact match", lambda m: pct(m["sequence"]["exact"])),
        ("Sequence similarity (mean LCS ratio)", lambda m: f"{m['sequence']['mean_lcs_ratio']:.3f}"),
    ]
    for name, fn in rows:
        out.append(f"| {name} | " + " | ".join(fn(m) for m in report["scores"].values()) + " |")
    out.append("")
    for suite, m in report["scores"].items():
        ci = m["bootstrap_95ci"]
        out += [f"### {suite}: 95% bootstrap intervals (case resampling, 1000 draws)", "",
                f"status accuracy {pct(ci['status_accuracy'][0])}–{pct(ci['status_accuracy'][1])}, "
                f"step F1 {ci['step_f1'][0]:.3f}–{ci['step_f1'][1]:.3f}, "
                f"sequence exact {pct(ci['sequence_accuracy'][0])}–{pct(ci['sequence_accuracy'][1])}", "",
                "Status confusion (rows = expected, columns = predicted):", "",
                "| | COMPLETE | INCOMPLETE | NOT_APPLICABLE | other |", "|---|---|---|---|---|"]
        for exp, row in m["status"]["confusion"].items():
            out.append(f"| {exp} | " + " | ".join(str(v) for v in row.values()) + " |")
        out += ["", "Step accuracy by phase and operation:", "", "| Bucket | Precision | Recall | F1 | Support |",
                "|---|---|---|---|---|"]
        for bucket in ("steps_by_phase", "steps_by_operation"):
            for b, v in m[bucket].items():
                out.append(f"| {b} | {pct(v['precision'])} | {pct(v['recall'])} | {v['f1']:.3f} | {v['tp'] + v['fn']} |")
        if m["failures"]:
            out += ["", "Failing cases:", "", "| Case | Expected | Got | Missing steps | Extra steps |",
                    "|---|---|---|---|---|"]
            for f in m["failures"]:
                miss = "; ".join(f"{x[3]} {x[2]}" for x in f["missing"]) or "—"
                extra = "; ".join(f"{x[3]} {x[2]}" for x in f["extra"]) or "—"
                out.append(f"| {f['case_id']} | {f['exp_status']} | {f['got_status']} | {miss} | {extra} |")
        out.append("")
    out += ["## 2. Contract and evidence validation", "",
            "Checks every rule of the output contract plus plan coherence and evidence provenance "
            "(cited IDs must exist and be captured at or before the case's `audit_at`).", "",
            "| Predictions file | Rows | Violations | Result |", "|---|---|---|---|"]
    for name, c in report["contract"].items():
        detail = ", ".join(f"{k}: {v}" for k, v in c["by_rule"].items()) or "none"
        verdict = "PASS" if c["passed"] else "FAIL"
        if c["passed"] and c.get("warnings"):
            verdict += f" ({c['warnings']} warning{'s' if c['warnings'] > 1 else ''})"
        out.append(f"| {name} | {c['rows']} | {detail} | {verdict} |")
    out.append("")
    if report.get("metamorphic"):
        mm = report["metamorphic"]
        out += ["## 3. Metamorphic robustness (518 evaluation requests)", "",
                "Each perturbation must leave every answer unchanged.", "",
                "| Test | Result | Changed cases |", "|---|---|---|"]
        for name, r in mm.items():
            if name.startswith("_"):
                continue
            out.append(f"| {name} | {'PASS' if r['passed'] else 'FAIL'} | "
                       f"{r.get('changed_count', len(r['changed_cases']))} {', '.join(r['changed_cases'][:5])} |")
        out.append("")
    if report.get("regression"):
        out += ["## 4. Regression gate", "", f"Baseline: `evaluation/baseline.json`, tolerance {TOLERANCE}.", "",
                "| Suite | Metric | Baseline | Current | Result |", "|---|---|---|---|---|"]
        for r in report["regression"]:
            out.append(f"| {r['suite']} | {r['metric']} | {r['baseline']:.4f} | {r['current']:.4f} | "
                       f"{'PASS' if r['passed'] else 'FAIL'} |")
        out.append("")
    out += ["## Verdict", "", f"**{'PASS' if report['passed'] else 'FAIL'}** — " + report["verdict_reason"], ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="skip metamorphic robustness tests")
    ap.add_argument("--update-baseline", action="store_true")
    ap.add_argument("--score", type=Path, help="score an existing predictions CSV")
    ap.add_argument("--expected", type=Path)
    ap.add_argument("--requests", type=Path)
    args = ap.parse_args()

    if args.score:  # ad-hoc scoring of any predictions file
        m = metrics.evaluate(metrics.load_rows(args.expected), metrics.load_rows(args.score))
        res = {"scores": headline(m)}
        if args.requests:
            res["contract"] = contract.validate(args.score, args.requests, args.requests.parent)
        print(json.dumps(res, indent=2))
        return 0

    t0 = time.time()
    PRED_DIR.mkdir(exist_ok=True)
    report: dict = {"scores": {}, "contract": {}}
    for name, (ds, req, expected) in SUITES.items():
        pred = PRED_DIR / f"{name}_predictions.csv"
        metamorphic.run_agent(ds, ds / req, pred)
        report["scores"][name] = metrics.evaluate(metrics.load_rows(expected), metrics.load_rows(pred))
        report["contract"][f"{name}_predictions.csv"] = contract.validate(pred, ds / req, ds)
    eval_pred = PRED_DIR / "evaluation_predictions.csv"
    metamorphic.run_agent(REPO / "dataset", REPO / "dataset" / "deletion_requests.csv", eval_pred)
    report["contract"]["evaluation_predictions.csv (518)"] = contract.validate(
        eval_pred, REPO / "dataset" / "deletion_requests.csv", REPO / "dataset")
    if (REPO / "output.csv").exists():
        report["contract"]["output.csv (submitted)"] = contract.validate(
            REPO / "output.csv", REPO / "dataset" / "deletion_requests.csv", REPO / "dataset")
        report["submitted_matches_fresh_run"] = (REPO / "output.csv").read_bytes() == eval_pred.read_bytes()
    if not args.quick:
        report["metamorphic"] = metamorphic.run_all(REPO / "dataset")

    current = {s: headline(m) for s, m in report["scores"].items()}
    if args.update_baseline or not BASELINE.exists():
        BASELINE.write_text(json.dumps(current, indent=2), encoding="utf-8")
    baseline = json.loads(BASELINE.read_text(encoding="utf-8"))
    report["regression"] = [
        {"suite": s, "metric": k, "baseline": baseline[s][k], "current": v, "passed": v >= baseline[s][k] - TOLERANCE}
        for s, metrics_now in current.items() if s in baseline for k, v in metrics_now.items() if k in baseline[s]]

    reasons = []
    if not all(c["passed"] for c in report["contract"].values()):
        reasons.append("contract violations")
    if report.get("metamorphic") and report["metamorphic"]["_summary"]["passed"] != report["metamorphic"]["_summary"]["tests"]:
        reasons.append("robustness failures")
    if not all(r["passed"] for r in report["regression"]):
        reasons.append("metric regression")
    if report.get("submitted_matches_fresh_run") is False:
        reasons.append("submitted output.csv differs from a fresh run")
    report["passed"] = not reasons
    report["verdict_reason"] = "; ".join(reasons) if reasons else (
        "all contract checks, robustness tests" + ("" if args.quick else "") + " and regression gates passed; "
        "submitted output.csv is byte-identical to a fresh run.")
    report["seconds"] = round(time.time() - t0, 1)
    (HERE / "results.json").write_text(json.dumps(report, indent=2, default=list), encoding="utf-8")
    (HERE / "harness_report.md").write_text(render(report), encoding="utf-8")
    print(json.dumps({"passed": report["passed"], "verdict": report["verdict_reason"],
                      "scores": current, "seconds": report["seconds"],
                      "report": str(HERE / "harness_report.md")}, indent=2))
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
